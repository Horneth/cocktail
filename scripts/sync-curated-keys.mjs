// Regenerate functions/shared/curatedKeys.mjs from scripts/classics.json.
//
// The deployed function can only import from inside functions/, so the
// curated-keys set ships as a derived file there. This script is the only way
// it's written; a test in src/domain (poolSharedSync.test.ts) fails the build
// if the file and classics.json ever disagree.
//
//   npm run images:sync-keys    # after editing scripts/classics.json

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { poolKeyForName } from '../src/domain/poolKey.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const classics = JSON.parse(readFileSync(resolve(root, 'scripts/classics.json'), 'utf8'))

const keys = [...new Set(classics.map((c) => poolKeyForName(c.name)))].sort()

const out = `// GENERATED by scripts/sync-curated-keys.mjs — do not edit by hand.
// The drink keys the curated seeder owns: on-demand generation refuses these
// (the seeder publishes their shot; until then they render the spirit tile).
// Derived from scripts/classics.json; poolSharedSync.test.ts enforces sync.

export const CURATED_KEYS = new Set([
${keys.map((k) => `  '${k}',`).join('\n')}
])
`
writeFileSync(resolve(root, 'functions/shared/curatedKeys.mjs'), out)
console.log(`${keys.length} curated keys → functions/shared/curatedKeys.mjs`)